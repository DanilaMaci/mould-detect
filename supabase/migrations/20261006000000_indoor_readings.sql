-- mould-detect: indoor_readings table (first schema, applied 2026-10-06)
-- Run in the Supabase SQL Editor, or with `supabase db push`.

-- Indoor measurements sent by the ESP32 sensor node
create table public.indoor_readings (
    id           bigint generated by default as identity primary key,
    received_at  timestamptz not null default now(),   -- when it arrived at the database
    measured_at  timestamptz not null default now(),   -- when measured (device time, once SNTP is added)
    device_id    text        not null,
    temp_c       real        not null,
    rh           real        not null,
    press_hpa    real        not null,
    rssi_dbm     smallint,                              -- Wi-Fi signal, to explain data gaps
    constraint temp_c_range    check (temp_c between -40 and 85),
    constraint rh_range        check (rh between 0 and 100),
    constraint press_hpa_range check (press_hpa between 300 and 1100)
);

comment on table public.indoor_readings is 'ESP32 measurements';

-- Fast time-range queries (dashboard and ML)
create index indoor_readings_measured_at_idx
    on public.indoor_readings (measured_at);

-- Security, lock 1 (GRANT): the public (anon) key may only INSERT
grant insert on table public.indoor_readings to anon;

-- Security, lock 2 (RLS): row level security on, with one insert-only policy
alter table public.indoor_readings enable row level security;

create policy "device can insert readings"
    on public.indoor_readings
    for insert
    to anon
    with check (true);